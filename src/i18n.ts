export type Lang = 'zh' | 'en';

const tables: Record<Lang, Record<MsgKey, string>> = { en, zh };

export function detectLang(): Lang {
  const l = (navigator.language || 'en').toLowerCase();
  return l.startsWith('zh') ? 'zh' : 'en';
}

export function hasKey(key: string): key is MsgKey {
  return key in en;
}

export function translate(lang: Lang, key: MsgKey, params?: Record<string, string | number>): string {
  let s = tables[lang][key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export type TFunc = (key: MsgKey, params?: Record<string, string | number>) => string;
